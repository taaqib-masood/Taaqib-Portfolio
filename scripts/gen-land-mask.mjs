// Generates src/lib/land-mask.ts: a 360×180 (1°) land/ocean bitmap for the hero globe.
// One-off tool, deliberately not a project dependency. To rerun:
//   mkdir /tmp/landgen && cd /tmp/landgen && npm i world-atlas@2 topojson-client@3 d3-geo@3
//   NODE_PATH=/tmp/landgen/node_modules node scripts/gen-land-mask.mjs
import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";
import path from "node:path";

const require = createRequire(path.join(process.env.NODE_PATH ?? "", "x.js"));
const { feature } = require("topojson-client");
const { geoContains } = require("d3-geo");
const land = feature(require("world-atlas/land-50m.json"), "land");

const W = 360, H = 180;
const bits = new Uint8Array((W * H) / 8);
for (let y = 0; y < H; y++)
  for (let x = 0; x < W; x++) {
    const lon = x - 180 + 0.5, lat = 90 - y - 0.5; // cell centres
    if (geoContains(land, [lon, lat])) bits[(y * W + x) >> 3] |= 1 << (x & 7);
  }

writeFileSync(new URL("../src/lib/land-mask.ts", import.meta.url), `// Generated by scripts/gen-land-mask.mjs from Natural Earth 50m land (world-atlas). Do not edit.
// 360×180 bits, row-major from 90°N, 1° cells: bit (y * 360 + x) set means land.
const MASK = "${Buffer.from(bits).toString("base64")}";

let bytes: Uint8Array | null = null;

/** True if the 1° cell containing (lat, lon) is land. */
export function isLand(lat: number, lon: number): boolean {
  bytes ??= Uint8Array.from(atob(MASK), (c) => c.charCodeAt(0));
  const x = Math.min(359, Math.max(0, Math.floor(lon + 180)));
  const y = Math.min(179, Math.max(0, Math.floor(90 - lat)));
  const i = y * 360 + x;
  return (bytes[i >> 3] & (1 << (i & 7))) !== 0;
}
`);
console.log("land cells:", bits.reduce((n, b) => n + b.toString(2).split("1").length - 1, 0), "of", W * H);
